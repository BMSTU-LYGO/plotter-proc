std::string fixed(double value, std::uint32_t decimals) {
    std::array<char, 128> buffer{};
    const auto [end, error] = std::to_chars(buffer.data(), buffer.data() + buffer.size(),
                                            value, std::chars_format::fixed,
                                            static_cast<int>(decimals));
    if (error != std::errc{}) throw std::invalid_argument("Cannot format G-code coordinate");
    return {buffer.data(), end};
}

std::string seconds_text(double value) {
    std::ostringstream stream;
    stream.imbue(std::locale::classic());
    stream << std::setprecision(12) << value;
    return stream.str();
}

void append_unique(std::vector<std::string>& lines, const std::string& line) {
    if (lines.empty() || lines.back() != line) lines.push_back(line);
}

void ensure_workspace(Point point, const WorkspaceConfig& workspace) {
    if (point.x.value < workspace.min_x.value || point.x.value > workspace.max_x.value ||
        point.y.value < workspace.min_y.value || point.y.value > workspace.max_y.value)
        throw std::invalid_argument("Page-change park point is outside workspace");
}

Point park_point(const PlotterJob& job, const MachineConfig& machine) {
    const auto& park = machine.page_change;
    if (park.park_mode == "machine_point") {
        ensure_workspace(park.park_machine_point, machine.workspace);
        return park.park_machine_point;
    }
    if (park.park_mode != "corner" || park.park_inset.value < 0.0)
        throw std::invalid_argument("Invalid page-change park mode or inset");
    const auto inset = park.park_inset;
    Point page{};
    if (park.park_corner == "top_left") page = {inset, inset};
    else if (park.park_corner == "top_right") page = {job.page_width - inset, inset};
    else if (park.park_corner == "bottom_left") page = {inset, job.page_height - inset};
    else if (park.park_corner == "bottom_right")
        page = {job.page_width - inset, job.page_height - inset};
    else throw std::invalid_argument("Invalid page-change park corner");
    PathDocument geometry;
    geometry.page_width = job.page_width;
    geometry.page_height = job.page_height;
    const Point machine_point = to_machine_point(page, geometry, machine);
    ensure_workspace(machine_point, machine.workspace);
    return machine_point;
}

std::vector<std::string> drawing_lines(const PathDocument& paths, const MachineConfig& machine) {
    const std::string single = generate_gcode(paths, machine);
    std::istringstream input(single);
    std::string line;
    std::vector<std::string> all;
    while (std::getline(input, line)) all.push_back(std::move(line));
    std::size_t first = 1;
    while (first < all.size() &&
           (all[first] == "G21" || all[first] == "G90" || all[first] == "G28")) ++first;
    if (first < all.size()) ++first; // The per-page initial pen-up belongs to the job header.
    if (all.size() < first + 3) throw std::runtime_error("Invalid single-page G-code body");
    return {all.begin() + static_cast<std::ptrdiff_t>(first), all.end() - 3};
}

