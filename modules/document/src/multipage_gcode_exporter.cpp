std::string generate_job_gcode(const PlotterJob& job, const MachineConfig& machine,
                               std::size_t max_commands) {
    if (job.pages.empty()) throw std::invalid_argument("Plotter job contains no pages");
    if (max_commands == 0) throw std::invalid_argument("max_commands must be positive");
    if (job.page_width.value <= 0.0 || job.page_height.value <= 0.0)
        throw std::invalid_argument("Plotter job page size must be positive");
    const auto decimals = machine.gcode.decimals;
    const std::string pen_up = "G0 Z" + fixed(machine.pen.up_z.value, decimals) +
                               " F" + fixed(machine.feedrate.z_mm_min, decimals);
    const std::string travel_feed = fixed(machine.feedrate.travel_mm_min, decimals);
    std::vector<std::string> lines{"; Generated by plotter-processor",
                                   "; Pages: " + std::to_string(job.pages.size())};
    if (machine.gcode.units_mm) lines.emplace_back("G21");
    if (machine.gcode.absolute_positioning) lines.emplace_back("G90");
    if (machine.gcode.home) lines.emplace_back("G28");
    lines.push_back(pen_up);
    for (std::size_t index = 0; index < job.pages.size(); ++index) {
        const auto& page = job.pages[index];
        if (page.paths.page_width.value != job.page_width.value ||
            page.paths.page_height.value != job.page_height.value)
            throw std::invalid_argument("Page geometry differs from job page size");
        const std::string label = std::to_string(index + 1) + "/" +
                                  std::to_string(job.pages.size());
        lines.push_back("; ===== PAGE " + label + " START =====");
        lines.push_back(pen_up);
        const auto drawing = drawing_lines(page.paths, machine);
        lines.insert(lines.end(), drawing.begin(), drawing.end());
        if (index + 1 == job.pages.size()) continue;
        if (!machine.page_change.enabled)
            throw std::invalid_argument("Multi-page output needs page-change behavior");
        if (machine.page_change.wait_command != "dwell" ||
            !std::isfinite(machine.page_change.pause_seconds) ||
            machine.page_change.pause_seconds < 0.0)
            throw std::invalid_argument("Invalid page-change wait behavior");
        append_unique(lines, pen_up);
        lines.push_back("; PAGE " + label + " COMPLETE");
        const Point park = park_point(job, machine);
        lines.push_back("G0 X" + fixed(park.x.value, decimals) + " Y" +
                        fixed(park.y.value, decimals) + " F" + travel_feed);
        lines.emplace_back("M400");
        lines.push_back("; CHANGE PAPER - WAIT " +
                        seconds_text(machine.page_change.pause_seconds) + " SECONDS");
        lines.push_back("G4 P" + std::to_string(static_cast<long long>(
            std::nearbyint(machine.page_change.pause_seconds * 1000.0))));
        if (lines.size() > max_commands) throw std::length_error("G-code command limit exceeded");
    }
    append_unique(lines, pen_up);
    lines.emplace_back("M400");
    lines.emplace_back("M84");
    lines.emplace_back("; End");
    if (lines.size() > max_commands) throw std::length_error("G-code command limit exceeded");
    std::size_t byte_count = 0;
    for (const auto& line : lines) byte_count += line.size() + 1;
    std::string output;
    output.reserve(byte_count);
    for (const auto& line : lines) { output += line; output += '\n'; }
    return output;
}

